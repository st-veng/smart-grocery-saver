/** Savings-ledger helpers: dashboard buckets and a safe CSV writer (SPEC Phase 6). Pure. */
import { addDays, dayOfWeek, toDayNumber, type IsoDate } from '../dates.js';

export type BucketInterval = 'week' | 'month';

/**
 * Start of the bucket containing `date`. Weeks start on Monday (ISO, same as Postgres
 * `date_trunc('week', …)`); months on the 1st. Dates are already America/Chicago calendar dates.
 */
export function bucketStart(date: IsoDate, interval: BucketInterval): IsoDate {
  if (interval === 'month') return `${date.slice(0, 7)}-01`;
  return addDays(date, -((dayOfWeek(date) + 6) % 7));
}

function nextBucket(start: IsoDate, interval: BucketInterval): IsoDate {
  if (interval === 'week') return addDays(start, 7);
  const y = Number(start.slice(0, 4));
  const m = Number(start.slice(5, 7));
  return m === 12 ? `${String(y + 1)}-01-01` : `${String(y)}-${String(m + 1).padStart(2, '0')}-01`;
}

/** Every bucket start from the bucket containing `from` through the one containing `to`. */
export function bucketsBetween(from: IsoDate, to: IsoDate, interval: BucketInterval): IsoDate[] {
  if (toDayNumber(from) > toDayNumber(to)) return [];
  const out: IsoDate[] = [];
  const last = bucketStart(to, interval);
  for (let b = bucketStart(from, interval); b <= last; b = nextBucket(b, interval)) out.push(b);
  return out;
}

/** A decimal we formatted ourselves (e.g. money "-1.05"): written verbatim, never escaped. */
export interface CsvDecimal {
  readonly decimal: string;
}
export type CsvCell = string | number | null | CsvDecimal;

/**
 * One CSV cell (RFC 4180). Text that a spreadsheet would run as a formula (leading = + - @, tab or
 * CR) gets a leading apostrophe (OWASP CSV injection). Numbers are written as numbers: they are
 * generated by us, never user text, and a negative saving must stay a number.
 */
export function csvCell(value: CsvCell): string {
  if (value === null) return '';
  if (typeof value === 'object') {
    if (!/^-?\d+(\.\d+)?$/.test(value.decimal)) throw new RangeError('Not a decimal');
    return value.decimal;
  }
  if (typeof value === 'number') {
    if (!Number.isFinite(value)) throw new RangeError('CSV numbers must be finite');
    return String(value);
  }
  const safe = /^[=+\-@\t\r]/.test(value) ? `'${value}` : value;
  return /[",\r\n]/.test(safe) || safe !== safe.trim() ? `"${safe.replaceAll('"', '""')}"` : safe;
}

/** RFC 4180: CRLF line breaks, including after the last record. */
export function toCsv(rows: readonly (readonly CsvCell[])[]): string {
  return rows.map((r) => r.map(csvCell).join(',')).join('\r\n') + '\r\n';
}

/** Dollars with two decimals for exports ("-1.05"). Integer cents in, exact string out. */
export function centsToDecimal(cents: number): CsvDecimal {
  return { decimal: formatDecimalCents(cents) };
}

export function formatDecimalCents(cents: number): string {
  const sign = cents < 0 ? '-' : '';
  const abs = Math.abs(Math.trunc(cents));
  return `${sign}${String(Math.floor(abs / 100))}.${String(abs % 100).padStart(2, '0')}`;
}
